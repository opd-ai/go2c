// generateIfThen generates an if-then statement (no else)
func (e *Emitter) generateIfThen(
	pattern *llvm.ControlFlowPattern,
	blocks map[string]*llvm.BasicBlock,
	patterns []*llvm.ControlFlowPattern,
	sb *strings.Builder,
	processed map[string]bool,
	indent int,
) {
	condBlock := blocks[pattern.CondBlock]
	thenBlock := blocks[pattern.ThenBlock]
	
	if condBlock == nil || thenBlock == nil {
		return
	}
	
	indentStr := strings.Repeat("    ", indent)
	
	// Generate instructions before the branch (excluding terminator)
	for i, inst := range condBlock.Instructions {
		// Skip the last instruction if it's the branch terminator
		if i == len(condBlock.Instructions)-1 && strings.HasPrefix(inst, "br") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			sb.WriteString(indentStr + cLine + "\n")
		}
	}
	
	// Generate if statement
	if condBlock.Terminator != nil && condBlock.Terminator.Condition != "" {
		condition := e.typeMapper.SanitizeName(condBlock.Terminator.Condition)
		sb.WriteString(fmt.Sprintf("%sif (%s) {\n", indentStr, condition))
		
		// Generate then block (all instructions except final unconditional branch to merge)
		for i, inst := range thenBlock.Instructions {
			// Skip unconditional branch to merge point
			if i == len(thenBlock.Instructions)-1 && strings.HasPrefix(inst, "br label") {
				break
			}
			cLine := e.convertInstructionToC(inst)
			if cLine != "" {
				sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
			}
		}
		
		sb.WriteString(fmt.Sprintf("%s}\n", indentStr))
		
		// Mark blocks as processed
		processed[pattern.ThenBlock] = true
		
		// Continue with merge block
		if pattern.EndLabel != "" && !processed[pattern.EndLabel] {
			e.generateBlockWithPatterns(pattern.EndLabel, blocks, patterns, sb, processed, indent)
		}
	}
}

// generateWhile generates a while loop
func (e *Emitter) generateWhile(
	pattern *llvm.ControlFlowPattern,
	blocks map[string]*llvm.BasicBlock,
	patterns []*llvm.ControlFlowPattern,
	sb *strings.Builder,
	processed map[string]bool,
	indent int,
) {
	condBlock := blocks[pattern.CondBlock]
	bodyBlock := blocks[pattern.BodyBlock]
	
	if condBlock == nil || bodyBlock == nil {
		return
	}
	
	indentStr := strings.Repeat("    ", indent)
	
	// Generate instructions in cond block before the branch (to compute condition)
	for i, inst := range condBlock.Instructions {
		// Skip the conditional branch at the end
		if i == len(condBlock.Instructions)-1 && strings.HasPrefix(inst, "br i1") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			sb.WriteString(indentStr + cLine + "\n")
		}
	}
	
	// Generate while loop
	if condBlock.Terminator != nil && condBlock.Terminator.Condition != "" {
		condition := e.typeMapper.SanitizeName(condBlock.Terminator.Condition)
		sb.WriteString(fmt.Sprintf("%swhile (%s) {\n", indentStr, condition))
		
		// Generate loop body (excluding the back-edge branch)
		for i, inst := range bodyBlock.Instructions {
			// Skip unconditional branch back to condition
			if i == len(bodyBlock.Instructions)-1 && strings.HasPrefix(inst, "br label") {
				break
			}
			cLine := e.convertInstructionToC(inst)
			if cLine != "" {
				sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
			}
		}
		
		// Re-evaluate condition at end of loop (for variables modified in body)
		for i, inst := range condBlock.Instructions {
			// Skip the conditional branch at the end
			if i == len(condBlock.Instructions)-1 && strings.HasPrefix(inst, "br i1") {
				break
			}
			cLine := e.convertInstructionToC(inst)
			if cLine != "" {
				sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
			}
		}
		
		sb.WriteString(fmt.Sprintf("%s}\n", indentStr))
		
		// Mark blocks as processed
		processed[pattern.CondBlock] = true
		processed[pattern.BodyBlock] = true
		
		// Continue with code after loop
		if pattern.EndLabel != "" && !processed[pattern.EndLabel] {
			e.generateBlockWithPatterns(pattern.EndLabel, blocks, patterns, sb, processed, indent)
		}
	}
}

// generateFor generates a for loop
func (e *Emitter) generateFor(
	pattern *llvm.ControlFlowPattern,
	blocks map[string]*llvm.BasicBlock,
	patterns []*llvm.ControlFlowPattern,
	sb *strings.Builder,
	processed map[string]bool,
	indent int,
) {
	initBlock := blocks[pattern.InitBlock]
	condBlock := blocks[pattern.CondBlock]
	bodyBlock := blocks[pattern.BodyBlock]
	incrBlock := blocks[pattern.IncrBlock]
	
	if initBlock == nil || condBlock == nil || bodyBlock == nil || incrBlock == nil {
		return
	}
	
	indentStr := strings.Repeat("    ", indent)
	
	// Generate initialization code (before for statement)
	var initStatements []string
	for i, inst := range initBlock.Instructions {
		// Skip the unconditional branch at the end
		if i == len(initBlock.Instructions)-1 && strings.HasPrefix(inst, "br label") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			initStatements = append(initStatements, cLine)
		}
	}
	
	// Generate condition evaluation code (to get the condition variable)
	var condStatements []string
	var conditionVar string
	for i, inst := range condBlock.Instructions {
		// Skip the conditional branch at the end
		if i == len(condBlock.Instructions)-1 && strings.HasPrefix(inst, "br i1") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			condStatements = append(condStatements, cLine)
			// Extract the variable name from assignment (last statement before condition)
			if strings.Contains(cLine, "bool") && strings.Contains(cLine, "=") {
				parts := strings.SplitN(cLine, "=", 2)
				if len(parts) == 2 {
					varPart := strings.TrimSpace(strings.TrimPrefix(parts[0], "bool"))
					conditionVar = strings.TrimSpace(varPart)
				}
			}
		}
	}
	
	// If we have a condition variable from the terminator
	if conditionVar == "" && condBlock.Terminator != nil && condBlock.Terminator.Condition != "" {
		conditionVar = e.typeMapper.SanitizeName(condBlock.Terminator.Condition)
	}
	
	// Generate increment code
	var incrStatements []string
	for i, inst := range incrBlock.Instructions {
		// Skip the unconditional branch back to condition
		if i == len(incrBlock.Instructions)-1 && strings.HasPrefix(inst, "br label") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			incrStatements = append(incrStatements, cLine)
		}
	}
	
	// Output initialization statements before the for loop
	for _, stmt := range initStatements {
		sb.WriteString(indentStr + stmt + "\n")
	}
	
	// Output condition evaluation before the for loop (for initial condition)
	for _, stmt := range condStatements {
		sb.WriteString(indentStr + stmt + "\n")
	}
	
	// Generate for loop with simplified structure
	// for (; condition; increment)
	sb.WriteString(fmt.Sprintf("%sfor (; %s; ", indentStr, conditionVar))
	
	// Write increment as inline expression (simplified)
	if len(incrStatements) > 0 {
		// Try to extract simple increment expression
		lastIncr := incrStatements[len(incrStatements)-1]
		// Remove semicolon and extract expression
		lastIncr = strings.TrimSuffix(lastIncr, ";")
		// Check if it's a simple assignment we can use
		if strings.Contains(lastIncr, "=") {
			parts := strings.SplitN(lastIncr, "=", 2)
			if len(parts) == 2 {
				sb.WriteString(strings.TrimSpace(parts[0]) + " = " + strings.TrimSpace(parts[1]))
			}
		}
	}
	sb.WriteString(") {\n")
	
	// Generate loop body (excluding the branch to increment)
	for i, inst := range bodyBlock.Instructions {
		// Skip unconditional branch to increment block
		if i == len(bodyBlock.Instructions)-1 && strings.HasPrefix(inst, "br label") {
			break
		}
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
		}
	}
	
	// Re-evaluate condition at end of loop body (for variables modified in body)
	for _, stmt := range condStatements {
		sb.WriteString(strings.Repeat("    ", indent+1) + stmt + "\n")
	}
	
	sb.WriteString(fmt.Sprintf("%s}\n", indentStr))
	
	// Mark blocks as processed
	processed[pattern.InitBlock] = true
	processed[pattern.CondBlock] = true
	processed[pattern.BodyBlock] = true
	processed[pattern.IncrBlock] = true
	
	// Continue with code after loop
	if pattern.EndLabel != "" && !processed[pattern.EndLabel] {
		e.generateBlockWithPatterns(pattern.EndLabel, blocks, patterns, sb, processed, indent)
	}
}

// generateBasicBlock generates a basic block as-is (fallback)
func (e *Emitter) generateBasicBlock(
	label string,
	block *llvm.BasicBlock,
	sb *strings.Builder,
	indent int,
) {
	indentStr := strings.Repeat("    ", indent)
	
	// Generate label
	if label != "entry" {
		sb.WriteString(fmt.Sprintf("%s%s:\n", indentStr, label))
	}
	
	// Generate instructions
	for _, inst := range block.Instructions {
		cLine := e.convertInstructionToC(inst)
		if cLine != "" {
			sb.WriteString(indentStr + cLine + "\n")
		}
	}
	
	// Generate terminator
	if block.Terminator != nil {
		var termInst string
		switch block.Terminator.Type {
		case "ret":
			termInst = "ret"
		case "br_uncon":
			termInst = fmt.Sprintf("br label %%%s", block.Terminator.UnconLabel)
		case "br_cond":
			termInst = fmt.Sprintf("br i1 %s, label %%%s, label %%%s",
				block.Terminator.Condition,
				block.Terminator.TrueLabel,
				block.Terminator.FalseLabel)
		}
		
		if termInst != "" {
			cLine := e.convertInstructionToC(termInst)
			if cLine != "" {
				sb.WriteString(indentStr + cLine + "\n")
			}
		}
	}
}

// generateSwitch generates a C switch statement
func (e *Emitter) generateSwitch(
	pattern *llvm.ControlFlowPattern,
	blocks map[string]*llvm.BasicBlock,
	patterns []*llvm.ControlFlowPattern,
	sb *strings.Builder,
	processed map[string]bool,
	indent int,
) {
	indentStr := strings.Repeat("    ", indent)
	
	// Mark the switch block itself as processed
	processed[pattern.StartLabel] = true
	
	// Get the switch value and sanitize it
	switchValue := e.typeMapper.SanitizeName(pattern.SwitchValue)
	
	// Generate switch statement
	sb.WriteString(fmt.Sprintf("%sswitch (%s) {\n", indentStr, switchValue))
	
	// Generate case statements
	for _, switchCase := range pattern.SwitchCases {
		caseBlock := blocks[switchCase.Label]
		if caseBlock == nil {
			continue
		}
		
		// Generate case label
		sb.WriteString(fmt.Sprintf("%scase %s:\n", indentStr, switchCase.Value))
		
		// Mark as processed
		processed[switchCase.Label] = true
		
		// Generate case body
		for _, inst := range caseBlock.Instructions {
			// Check if this is a return statement - if so, don't add break
			if strings.HasPrefix(inst, "ret") {
				cLine := e.convertInstructionToC(inst)
				if cLine != "" {
					sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
				}
				// No break needed after return
				continue
			}
			
			cLine := e.convertInstructionToC(inst)
			if cLine != "" {
				sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
			}
		}
		
		// Check if we need a break statement
		// Only add break if the case doesn't end with return or goto
		if caseBlock.Terminator != nil {
			if caseBlock.Terminator.Type == "br_uncon" {
				// Unconditional branch - could be fallthrough or break
				// For now, treat as explicit break unless it's to the next case
				// This is a simplified implementation
				sb.WriteString(strings.Repeat("    ", indent+1) + "break;\n")
			}
			// If terminator is "ret", no break needed (already handled above)
		} else {
			// No terminator, add break to be safe
			sb.WriteString(strings.Repeat("    ", indent+1) + "break;\n")
		}
	}
	
	// Generate default case
	if pattern.DefaultLabel != "" {
		defaultBlock := blocks[pattern.DefaultLabel]
		if defaultBlock != nil {
			sb.WriteString(fmt.Sprintf("%sdefault:\n", indentStr))
			
			// Mark as processed
			processed[pattern.DefaultLabel] = true
			
			// Generate default body
			for _, inst := range defaultBlock.Instructions {
				if strings.HasPrefix(inst, "ret") {
					cLine := e.convertInstructionToC(inst)
					if cLine != "" {
						sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
					}
					continue
				}
				
				cLine := e.convertInstructionToC(inst)
				if cLine != "" {
					sb.WriteString(strings.Repeat("    ", indent+1) + cLine + "\n")
				}
			}
			
			// Add break for default if needed
			if defaultBlock.Terminator != nil {
				if defaultBlock.Terminator.Type == "br_uncon" {
					sb.WriteString(strings.Repeat("    ", indent+1) + "break;\n")
				}
			} else {
				sb.WriteString(strings.Repeat("    ", indent+1) + "break;\n")
			}
		}
	}
	
	// Close switch statement
	sb.WriteString(fmt.Sprintf("%s}\n", indentStr))
}

// generateAggregateTypeDefinition generates a C struct definition for an aggregate type
func (e *Emitter) generateAggregateTypeDefinition(aggType *AggregateType) string {
	var sb strings.Builder
	
	sb.WriteString(fmt.Sprintf("typedef struct {\n"))
	
	// Generate fields
	for i, fieldType := range aggType.FieldTypes {
		cType := e.typeMapper.LLVMTypeToC(fieldType)
		sb.WriteString(fmt.Sprintf("    %s field%d;\n", cType, i))
	}
	
	sb.WriteString(fmt.Sprintf("} %s;", aggType.Name))
	
	return sb.String()
}

// convertInsertValueInstruction converts an insertvalue instruction to C
// Example: %result = insertvalue {i32, i32} undef, i32 %x, 0
// Becomes: result.field0 = x;
func (e *Emitter) convertInsertValueInstruction(instruction string) string {
	// Parse the instruction
	parts := strings.SplitN(instruction, "=", 2)
	if len(parts) != 2 {
		return fmt.Sprintf("/* %s */", instruction)
	}

	lhs := strings.TrimSpace(parts[0])
	rhs := strings.TrimSpace(parts[1])
	lhs = e.typeMapper.SanitizeName(lhs)

	// Parse: insertvalue {type} aggregate, type value, index
	// Example: insertvalue {i32, i32} undef, i32 %x, 0
	re := regexp.MustCompile(`insertvalue\s+(\{[^}]+\})\s+(\S+),\s+(\S+)\s+(\S+),\s+(\d+)`)
	matches := re.FindStringSubmatch(rhs)

	if len(matches) < 6 {
		return fmt.Sprintf("/* %s */", instruction)
	}

	aggregateType := matches[1]
	aggregateValue := matches[2]
	valueToInsert := matches[4]
	index := matches[5]

	// Get C type for aggregate
	cType := e.typeMapper.LLVMTypeToC(aggregateType)

	// Sanitize the value to insert (unless it's a literal)
	sanitizedValue := valueToInsert
	if _, err := strconv.Atoi(valueToInsert); err != nil {
		// It's a variable, sanitize it
		sanitizedValue = e.typeMapper.SanitizeName(valueToInsert)
	}

	// Handle "undef" - this means we're creating a new struct
	if aggregateValue == "undef" {
		// Declare the struct variable if it's the first insertvalue
		return fmt.Sprintf("%s %s; %s.field%s = %s;", cType, lhs, lhs, index, sanitizedValue)
	}

	// Otherwise, we're modifying an existing struct
	sanitizedAggregate := e.typeMapper.SanitizeName(aggregateValue)
	return fmt.Sprintf("%s %s = %s; %s.field%s = %s;", cType, lhs, sanitizedAggregate, lhs, index, sanitizedValue)
}

// convertExtractValueInstruction converts an extractvalue instruction to C
// Example: %val1 = extractvalue {i32, i32} %0, 0
// Becomes: int val1 = var_0.field0;
func (e *Emitter) convertExtractValueInstruction(instruction string) string {
	// Parse the instruction
	parts := strings.SplitN(instruction, "=", 2)
	if len(parts) != 2 {
		return fmt.Sprintf("/* %s */", instruction)
	}

	lhs := strings.TrimSpace(parts[0])
	rhs := strings.TrimSpace(parts[1])
	lhs = e.typeMapper.SanitizeName(lhs)

	// Parse: extractvalue {type} aggregate, index
	// Example: extractvalue {i32, i32} %0, 0
	re := regexp.MustCompile(`extractvalue\s+(\{[^}]+\})\s+(\S+),\s+(\d+)`)
	matches := re.FindStringSubmatch(rhs)

	if len(matches) < 4 {
		return fmt.Sprintf("/* %s */", instruction)
	}

	aggregateType := matches[1]
	aggregateValue := matches[2]
	index := matches[3]

	// Parse aggregate type to get field type
	fieldTypes := e.typeMapper.parseAggregateFields(aggregateType)
	indexInt, err := strconv.Atoi(index)
	if err != nil || indexInt >= len(fieldTypes) {
		return fmt.Sprintf("/* %s */", instruction)
	}

	fieldType := e.typeMapper.LLVMTypeToC(fieldTypes[indexInt])
	sanitizedAggregate := e.typeMapper.SanitizeName(aggregateValue)

	return fmt.Sprintf("%s %s = %s.field%s;", fieldType, lhs, sanitizedAggregate, index)
}
